function catUuid(n: number): string {
  return `10000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
}

function prodUuid(n: number): string {
  return `20000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
}

function varUuid(p: number, v: number): string {
  return `30000000-0000-4000-${String(p).padStart(4, '0')}-${String(v).padStart(12, '0')}`;
}

function imgUuid(p: number, i: number): string {
  return `40000000-0000-4000-${String(p).padStart(4, '0')}-${String(i).padStart(12, '0')}`;
}

